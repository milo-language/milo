// scripts/ts2milo.ts: a function that maps, an unsupported construct that fails with
// file:line, an override that is counted, and the frontend files that must stay portable.
import { describe, expect, test } from "bun:test";
import { mkdtempSync, writeFileSync, mkdirSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { Unsupported, summary, transpile } from "../scripts/ts2milo";
import { countViolations } from "../scripts/ts-portable";

function tmpTs(name: string, body: string): { file: string; dir: string } {
  const dir = mkdtempSync(join(tmpdir(), "ts2milo-"));
  const file = join(dir, name);
  writeFileSync(file, body);
  return { file, dir };
}

describe("ts2milo", () => {
  test("a plain function maps and is counted automatic", () => {
    const { file, dir } = tmpTs("tsm_add.ts", "export function add(a: number, b: number): number {\n  return a + b;\n}\n");
    const r = transpile([file], { overridesDir: join(dir, "none") });
    const out = r.files.get("tsm_add.milo")!;
    expect(out).toContain("pub fn add(a: i64, b: i64): i64 {");
    expect(out).toContain("return (a + b)");
    expect(out.startsWith("// GENERATED by scripts/ts2milo.ts")).toBe(true);
    expect(summary(r)).toContain("functions: 1 total, 1 automatic, 0 overrides = 100.0% automatic");
  });

  test("output is deterministic", () => {
    const { file, dir } = tmpTs("tsm_det.ts", "export function f(x: number): number {\n  let y = x;\n  y += 1;\n  return y;\n}\n");
    const a = transpile([file], { overridesDir: join(dir, "none") }).files.get("tsm_det.milo");
    const b = transpile([file], { overridesDir: join(dir, "none") }).files.get("tsm_det.milo");
    expect(a).toBe(b);
  });

  test("an unsupported construct fails with file:line and its name", () => {
    const { file } = tmpTs("tsm_bad.ts", "export function f(xs: number[]): number {\n  let n = 0;\n  for (const x of xs) { n += x; }\n  return n;\n}\n");
    let msg = "";
    try { transpile([file]); } catch (e) { expect(e).toBeInstanceOf(Unsupported); msg = (e as Error).message; }
    expect(msg).toContain("tsm_bad.ts:3: ForOfStatement");
  });

  test("an override replaces one function and is counted as not automatic", () => {
    const { file, dir } = tmpTs("tsm_ov.ts", "export function one(): number {\n  return 1;\n}\nexport function two(): number {\n  return 2;\n}\n");
    const ov = join(dir, "overrides");
    mkdirSync(ov);
    writeFileSync(join(ov, "tsm_ov.two.milo"), "pub fn two(): i64 {\n    return 22\n}\n");
    const r = transpile([file], { overridesDir: ov });
    const out = r.files.get("tsm_ov.milo")!;
    expect(out).toContain("return 22");
    expect(out).not.toContain("return 2\n");
    expect(summary(r)).toContain("functions: 2 total, 1 automatic, 1 overrides = 50.0% automatic");
    expect(summary(r)).toContain("override:");
  });
});

describe("ts-portable", () => {
  test("lexer and tokens stay inside the portable subset", () => {
    const res = countViolations(["src/lexer.ts", "src/tokens.ts"]);
    expect(res.get("src/lexer.ts")!.length).toBe(0);
    expect(res.get("src/tokens.ts")!.length).toBe(0);
  });
});
