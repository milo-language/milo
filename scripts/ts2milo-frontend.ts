// The self-host meter: generate the whole Milo frontend from src/*.ts (ts2milo --lenient, so
// what does not translate yet becomes a stub that names itself), compile-check every generated
// file, and print one number: compile errors left. Stubs compile, so this reaches 0 before
// everything is translated; after that the number that matters is which stub a real program
// hits first (--run).
//   bun scripts/ts2milo-frontend.ts            regenerate + check: errors per file and total
//   bun scripts/ts2milo-frontend.ts --top 15   also the most common error messages
//   bun scripts/ts2milo-frontend.ts --stub-errors      also stub every function that holds a compile error
//                                                   (its reason is the error), round after round until
//                                                   the tree compiles: the stubs are the worklist
//   bun scripts/ts2milo-frontend.ts --run <file.milo>   build the generated frontend and run it
//                                                        on one program (needs 0 errors)
import { readdirSync } from "fs";
import { join } from "path";
import { frontendFiles } from "./ts-portable";
import { transpile } from "./ts2milo";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "out", "ts2milo-all");
const argv = process.argv.slice(2);
const top = argv.includes("--top") ? Number(argv[argv.indexOf("--top") + 1]) : 0;

const files = ["src/ast.ts", ...frontendFiles().filter((f) => f !== "src/ast.ts")];
const stubNames = new Map<string, string>();
type Err = { file: string; line: number | undefined; message: string };
const generateAndCheck = async () => {
const r = transpile(files, { astRoots: ["Program"], lenient: true, stubNames });
await Bun.$`rm -rf ${OUT}`.quiet();
for (const [name, text] of r.files) await Bun.write(join(OUT, name), text);
const stubbed = new Set(r.stubs.map((s) => s.file + "::" + s.name));
const translated = r.functions.filter((f) => !stubbed.has(f.file + "::" + f.name) && !stubbed.has(f.file + "::" + f.name.split(".").pop())).length;

// `milo check` on one file follows its imports, so an error in a shared file shows up under
// every importer: errors are counted by (file, line, message) across all runs.
const seen = new Map<string, string>();
const firstOf = new Map<string, string>();
const errs: Err[] = [];
const gen = readdirSync(OUT).filter((f) => f.endsWith(".milo")).sort();
await Promise.all(gen.map(async (f) => {
  const p = Bun.spawn(["bun", join(ROOT, "src/main.ts"), "check", join(OUT, f), "--json"], { cwd: ROOT, stdout: "pipe", stderr: "pipe" });
  const text = await new Response(p.stdout).text();
  await p.exited;
  try {
    const j = JSON.parse(text) as { diagnostics: { severity: string; message: string; file?: string; line?: number }[] };
    for (const d of j.diagnostics) if (d.severity === "error") {
      const where = (d.file ?? f).replace(/.*\//, "");
      const key = `${where}:${d.line}:${d.message}`;
      if (!seen.has(key)) errs.push({ file: where, line: d.line, message: d.message });
      seen.set(key, d.message);
      if (!firstOf.has(where)) firstOf.set(where, `${d.line}: ${d.message.slice(0, 100)}`);
    }
  } catch {
    seen.set(`${f}:?:no json`, "check produced no JSON (crash?)");
  }
}));
return { r, translated, seen, firstOf, errs };
};

// A compile error at a line of a generated fn becomes a stub of that fn (by its TS file and name), so
// the next round compiles around it. Errors outside a fn (a struct, an import) cannot be stubbed this way.
const stubFor = async (e: Err): Promise<boolean> => {
  if (e.line === undefined) return false;
  const text = await Bun.file(join(OUT, e.file)).text().catch(() => "");
  const lines = text.split("\n");
  const src = /GENERATED by scripts\/ts2milo\.ts from (\S+?)\. /.exec(lines[0] ?? "")?.[1];
  if (!src) return false;
  for (let i = Math.min(e.line, lines.length) - 1; i >= 0; i--) {
    const m = /^\s*(?:pub )?fn ([A-Za-z_][A-Za-z0-9_]*)\(/.exec(lines[i]);
    if (m) {
      const key = `${src}::${m[1]}`;
      if (stubNames.has(key)) return false;
      stubNames.set(key, `compile error: ${e.message.slice(0, 160)}`);
      return true;
    }
    if (/^(pub )?(struct|enum|impl) /.test(lines[i]) && i < e.line - 1 && !/^impl /.test(lines[i])) return false;
  }
  return false;
};

let round = await generateAndCheck();
if (argv.includes("--stub-errors")) {
  for (let n = 1; n <= 12; n++) {
    let added = 0;
    for (const e of round.errs) if (await stubFor(e)) added++;
    if (!added) break;
    console.error(`--stub-errors round ${n}: stubbed ${added} more fns, regenerating`);
    round = await generateAndCheck();
  }
}
const { r, translated, seen, firstOf } = round;
const perFile = new Map<string, number>();
for (const k of seen.keys()) { const f = k.split(":")[0]; perFile.set(f, (perFile.get(f) ?? 0) + 1); }
for (const [f, n] of [...perFile].sort((a, b) => b[1] - a[1])) console.log(`${String(n).padStart(5)}  ${f}   first: ${firstOf.get(f) ?? ""}`);
console.log(`translated ${translated} of ${r.functions.length} functions, ${r.stubs.length} stubs${stubNames.size ? ` (${stubNames.size} of them compile-error stubs)` : ""}`);
if (process.env.DUMP_ERRORS) await Bun.write(process.env.DUMP_ERRORS, [...seen.keys()].sort().join("\n"));
console.log(`COMPILE ERRORS: ${seen.size}`);
if (top) {
  const byMsg = new Map<string, number>();
  for (const m of seen.values()) { const k = m.replace(/'[^']*'/g, "_").slice(0, 90); byMsg.set(k, (byMsg.get(k) ?? 0) + 1); }
  for (const [m, n] of [...byMsg].sort((a, b) => b[1] - a[1]).slice(0, top)) console.log(`${String(n).padStart(5)}  ${m}`);
}
if (argv.includes("--run")) {
  // Builds only what the driver imports, so a stage that compiles can run before the whole tree does.
  const prog = argv[argv.indexOf("--run") + 1];
  await Bun.write(join(OUT, "frontend-driver.milo"), Bun.file(join(ROOT, "scripts/ts2milo/frontend-driver.milo")));
  const bin = join(OUT, "frontend");
  const build = () => Bun.spawnSync(["bun", join(ROOT, "src/main.ts"), "build", join(OUT, "frontend-driver.milo"), "-o", bin], { cwd: ROOT, stdout: "pipe", stderr: "pipe" });
  let b = build();
  // A function the MLIR backend does not cover yet ("mlir: F is not covered: why") is stubbed like a
  // compile error, so the binary builds; with --stub-errors, round after round. Each is a backend gap.
  for (let n = 1; b.exitCode && argv.includes("--stub-errors") && n <= 40; n++) {
    const m = /mlir: ([A-Za-z_][A-Za-z0-9_$.]*) is not covered: ([^\n]*)/.exec(b.stderr.toString());
    if (!m) break;
    // A name with "$" is code the compiler synthesized (a derived Clone, a monomorphized copy): no TS function to
    // stub, the backend itself must learn the shape.
    if (m[1].includes("$")) { console.error(`--run: backend gap in synthesized ${m[1]}: ${m[2].slice(0, 120)}`); break; }
    const fn = m[1].replace(/^.*\./, "");
    const owner = [...r.functions].find((f) => f.name === fn || f.name.endsWith("." + fn));
    if (!owner) { console.error(`--run: cannot map backend gap in ${m[1]} to a TS function`); break; }
    const key = `${owner.file}::${owner.name.split(".").pop()}`;
    if (stubNames.has(key)) break;
    stubNames.set(key, `backend not covered: ${m[2].slice(0, 140)}`);
    console.error(`--run: backend gap ${n}: ${owner.file} ${fn}: ${m[2].slice(0, 100)}`);
    round = await generateAndCheck();
    await Bun.write(join(OUT, "frontend-driver.milo"), Bun.file(join(ROOT, "scripts/ts2milo/frontend-driver.milo")));
    b = build();
  }
  if (b.exitCode) { console.error("build failed:\n" + b.stderr.toString().split("\n").filter((l) => /error/.test(l)).slice(0, 8).join("\n")); process.exit(1); }
  const run = Bun.spawnSync([bin, prog], { cwd: ROOT, stdout: "inherit", stderr: "inherit" });
  process.exit(run.exitCode ?? 1);
}
