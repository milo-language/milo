// Renders the Homebrew formula for a release and prints it to stdout.
//
//   bun scripts/render-formula.ts <version> <artifacts-dir> [commit] > milo.rb
//
// <artifacts-dir> holds the milo-<target>.tar.gz files, which are hashed here rather
// than passed in — a formula whose sha256 doesn't match what the release actually
// serves is the classic tap breakage, and reading the bytes makes it impossible.
//
// The output goes in milo-language/homebrew-tap as Formula/milo.rb, so users get
// `brew install milo-language/tap/milo`. A tap needs no review; homebrew-core (bare
// `brew install milo`) has a notability bar Milo hasn't cleared yet.

import { createHash } from "crypto";
import { readFileSync } from "fs";
import { join } from "path";
import { TARGETS, tarballUrl } from "./release-meta";

const [version, artifacts, commitArg] = process.argv.slice(2);
if (!version || !artifacts) {
  console.error("usage: render-formula.ts <version> <artifacts-dir> [commit]");
  process.exit(1);
}
// Homebrew's `version` has to stay clean semver for its comparison rules, so the
// commit rides along as a comment rather than in the version string. It is still the
// thing you need when a tap user reports a bug against "0.1.0".
const commit = (commitArg ?? process.env.GITHUB_SHA ?? "").slice(0, 7);

const sha = (target: string) =>
  createHash("sha256")
    .update(readFileSync(join(artifacts, `milo-${target}.tar.gz`)))
    .digest("hex");

// The tarball unpacks to a milo-<target>/ directory, so the install path is not a bare
// `bin.install "milo"` — it has to reach inside.
const arm = (os: string) => TARGETS.find(t => t.os === os && t.cpu === "arm64")!.target;
const intel = (os: string) => TARGETS.find(t => t.os === os && t.cpu === "x64")!.target;

const block = (target: string, indent: string) =>
  [
    `${indent}url "${tarballUrl(version, target)}"`,
    `${indent}sha256 "${sha(target)}"`,
  ].join("\n");

process.stdout.write(`# Generated by scripts/render-formula.ts — do not edit by hand.
${commit ? `# milo ${version}, built from commit ${commit}.\n` : ""}class Milo < Formula
  desc "Memory-safe systems language that compiles to LLVM IR"
  homepage "https://milo-language.github.io/milo/"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block(arm("darwin"), "      ")}
    end
    on_intel do
${block(intel("darwin"), "      ")}
    end
  end

  on_linux do
    on_arm do
${block(arm("linux"), "      ")}
    end
    on_intel do
${block(intel("linux"), "      ")}
    end
  end

  # milo compiles through MLIR by default: milo-opt (shipped beside milo, statically linked)
  # produces the function bodies and the clang of Homebrew's LLVM compiles the module
  # (docs/mlir-backend.md), so llvm is a real dependency, not just a linker driver.
  depends_on "llvm"

  def caveats
    <<~EOS
      milo compiles with the clang of Homebrew's llvm (brew install llvm).
      The Intel macOS archive ships no milo-opt: build it (sh mlir/build.sh in a milo
      checkout) and put it beside the milo binary.
    EOS
  end

  def install
    # Homebrew strips a single root directory when it stages a tarball, so the binary
    # normally lands at the top level; the nested path is the fallback if that changes.
    src = File.exist?("milo") ? "milo" : Dir["milo-*/milo"].first
    bin.install src => "milo"
    opt = File.exist?("milo-opt") ? "milo-opt" : Dir["milo-*/milo-opt"].first
    bin.install opt => "milo-opt" if opt
  end

  test do
    assert_match "milo ${version}", shell_output("#{bin}/milo --version")
    (testpath/"hello.milo").write <<~MILO
      pub fn main(): i32 {
          print("hello")
          return 0
      }
    MILO
    # emit-ir, not run: the brew test sandbox has no guarantee of a working linker,
    # and everything up to the link is what this is checking.
    assert_match "define i32 @main", shell_output("#{bin}/milo emit-ir hello.milo")
  end
end
`);
